const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("playwright");

async function main() {
  const base = "http://127.0.0.1:"+process.env.ADW_TEST_PORT;
  const out = path.join(__dirname,"../../修复验证_20261108");
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH,headless:true});
  try {
    const context=await browser.newContext({viewport:{width:1440,height:900}});
    const page=await context.newPage();
    const faults=[];
    page.on("pageerror",e=>faults.push(e.message));
    const query=async(name)=>(await page.request.get(base+"/api/q/"+name)).json();
    assert.match((await query("storage_status")).dataDir,/\/adw-workflows-[^/]+\/data$/);
    const [project]=await query("list_projects");
    const eid=project.recent[0].id;
    const nav=page.getByRole("navigation",{name:"主导航"});
    const link=name=>nav.getByRole("link",{name,exact:true});
    const btn=name=>page.getByRole("button",{name,exact:true});
    const go=async route=>{await page.goto(base+"/#/"+route);await nav.waitFor();};
    await go("e/"+eid+"/story");
    const assistant=page.locator(".assistant:visible");
    const input=assistant.locator("textarea");
    await input.fill("核对站台里的雨伞，保留这条未发送的修改。");
    await btn("专注对话").click();
    assert.equal(await page.locator(".catalog:visible,.center:visible,.colgrip:visible").count(),0);
    assert.match(await input.inputValue(),/站台/);
    await link("导演风格与色卡").click();
    await page.getByRole("heading",{name:"导演风格与色卡",exact:true}).waitFor();
    await link("剧本知识库").click();
    await page.getByRole("heading",{name:"剧本知识库",exact:true}).waitFor();
    await link("界面与快捷键").click();
    await page.getByRole("heading",{name:"界面与快捷键"}).waitFor();
    assert.equal(await page.getByRole("checkbox",{name:"专注对话"}).isChecked(),true);
    await btn("放大字号").click();
    assert.equal(await page.locator("html").evaluate(el=>getComputedStyle(el).fontSize),"15px");
    const heading=page.getByRole("heading",{name:"界面与快捷键"});
    assert.ok(await heading.evaluate(el=>parseFloat(getComputedStyle(el).fontSize)>22));
    await page.reload();
    await heading.waitFor();
    assert.equal(await page.locator("output").innerText(),"15 px");
    await btn("放大字号").click();
    assert.ok(await btn("放大字号").isDisabled());
    await btn("恢复默认字号").click();
    await btn("缩小字号").click();
    assert.ok(await btn("缩小字号").isDisabled());
    await btn("恢复默认字号").click();
    await link("导演工作区").click();
    await btn("返回成果文档").waitFor();
    assert.match(await input.inputValue(),/站台/);
    const shot=await assistant.boundingBox();
    assert.ok(shot.width>=820);
    await page.screenshot({path:path.join(out,"17_单集专注对话.png")});
    await page.keyboard.press("Escape");
    await page.locator(".center:visible").waitFor();
    assert.match(await input.inputValue(),/站台/);
    await btn("专注对话").click();
    await assistant.getByRole("link",{name:"定位",exact:true}).first().click();
    await page.locator(".center:visible").waitFor();
    assert.ok(new URLSearchParams(new URL(page.url()).hash.split("?")[1]).has("v"));
    const layouts=[];
    for(const width of [1440,1280,1024,800]) {
      await page.setViewportSize({width,height:900});
      assert.equal(await nav.count(),1);
      assert.equal(await link("资产库").getAttribute("href"),"#/p/"+project.id+"/library");
      await nav.getByRole("button",{name:"展开主导航"}).click();
      await page.getByRole("button",{name:"收起主导航"}).waitFor();
      await page.keyboard.press("Escape");
      assert.equal(await nav.getByRole("button",{name:"展开主导航"}).evaluate(el=>el===document.activeElement),true);
      const content=await page.locator(".center:visible").boundingBox();
      assert.ok(content.width>320,"成果文档可用宽度 "+content.width);
      const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
      assert.equal(overflow,false);
      layouts.push({width,documentWidth:Math.round(content.width),bodyOverflow:overflow});
    }
    await btn("创作对话").click();
    await btn("成果文档").click();
    await nav.getByRole("button",{name:"展开主导航"}).click();
    await link("选题池").click();
    await page.waitForURL("**/p/"+project.id+"/topics");
    await page.getByRole("heading",{name:"选题池与研究"}).waitFor();
    assert.equal(await link("选题池").getAttribute("aria-current"),"page");
    await page.setViewportSize({width:1440,height:900});
    await link("设置").click();
    await page.locator("main").getByRole("link",{name:"图像通道"}).click();
    await page.getByRole("cell",{name:"隔离测试通道"}).waitFor();
    await btn("刷新通道状态").click();
    await link("设置").click();
    await page.locator("main").getByRole("link",{name:"H3 打包器"}).click();
    await page.getByText("可读取，三个打包入口齐全").waitFor();
    await page.getByText("暂无可追溯的出包记录").waitFor();
    await btn("重新检查打包器").click();
    const token=(await (await page.request.get(base+"/api/session")).json()).token;
    const pack=await page.request.post(base+"/api/cmd/package",{headers:{"x-adw-token":token},
      data:{delivery_id:project.deliveries[0].id,segments:["G01"],command_id:"navigation-offline-package"}});
    assert.equal(pack.status(),200,await pack.text());
    const packageId=(await pack.json()).packageId;
    await btn("重新检查打包器").click();
    await page.getByText(packageId,{exact:false}).waitFor();
    await page.screenshot({path:path.join(out,"19_H3打包器与此版本出包记录.png")});
    await link("界面与快捷键").click();
    await heading.waitFor();
    await page.screenshot({path:path.join(out,"18_统一导航与界面设置.png")});
    assert.deepEqual(faults,[]);
    fs.writeFileSync(path.join(out,"界面导航与专注对话验收.json"),JSON.stringify({layouts,defaultFontPx:13,
      selectedSizeAfterReload:15,testedBounds:[12,17],focusDraftPreserved:true,navigation:["导演风格与色卡","剧本知识库","界面与快捷键","导演工作区","选题池"],runtimeErrors:faults},null,2)+"\n");
    console.log("PASS navigation, persisted font size, focus mode, original draft and four viewport sizes",layouts);
  } finally {await browser.close();}
}
main().catch(e=>{console.error(e);process.exitCode=1;});
