// Exercise stage selections from the normal UI, using the isolated test service.
const assert = require("node:assert/strict");
const { chromium } = require("playwright");
const base = "http://127.0.0.1:" + process.env.ADW_TEST_PORT;

async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, headless: true });
  try {
    const page = await browser.newPage();
    const q = async (name, args={}) => {
      const res = await page.request.get(base+"/api/q/"+name, {params:{args:JSON.stringify(args)}});
      assert.equal(res.status(),200);
      return res.json();
    };
    assert.match((await q("storage_status")).dataDir,/\/adw-workflows-[^/]+\/data$/);
    const [project] = await q("list_projects");
    const episode = project.recent[0].id;
    const preview = "#/e/"+episode;
    const errors = [];
    page.on("pageerror",e=>errors.push(e.message));
    page.setDefaultTimeout(7000);
    await page.goto(base);
    await page.getByRole("link",{name:"全部 ›",exact:true}).click();
    await page.locator('a.projcard[href="#/p/'+project.id+'"]').waitFor();
    await page.goBack();
    await page.locator("main.home").getByRole("link",{name:"本地交付包",exact:true}).click();
    await page.locator('a[href="'+preview+'/delivery"]').first().click();
    await page.waitForURL("**/"+preview+"/delivery");
    await page.goto(base+"/"+preview+"/story");
    const btn = name => page.getByRole("button",{name,exact:true});
    for (const [width,stage,label] of [[1440,"story","必须保留的内容与结局方向"],[800,"script","必须承接的故事动作与角色选择"]]) {
      await page.setViewportSize({width,height:900});
      await page.goto(base+"/"+preview+"/"+stage);
      const views=page.getByRole("navigation",{name:"本阶段工作区"});
      await views.getByRole("button",{name:"创作对话"}).click();
      await page.locator(".assistant:visible textarea").fill(stage+" 暂存草稿");
      await views.getByRole("button",{name:"本步需求与参考"}).click();
      await page.getByLabel(label,{exact:true}).waitFor();
      await page.locator(".modal").getByRole("button",{name:"关闭",exact:true}).click();
      await views.getByRole("button",{name:"成果文档"}).click();
      await page.locator(".center:visible").waitFor();
      await views.getByRole("button",{name:"创作对话"}).click();
      assert.equal(await page.locator(".assistant:visible textarea").inputValue(),stage+" 暂存草稿");
      await views.getByRole("button",{name:"成果文档"}).click();
    }
    await page.setViewportSize({width:1440,height:900});
    await page.goto(base+"/"+preview+"/story");
    await btn("阶段技能").click();
    await page.getByLabel("显示全部阶段的方法").check();
    assert.equal(await page.locator("fieldset").getByRole("checkbox").count(),72);
    await page.getByLabel("必须保留的内容与结局方向").fill("保留最后一声关门");
    await page.getByRole("checkbox",{name:/00-A ·/}).check();
    await btn("保存本步配置").click();
    await page.getByRole("heading",{name:"本步需求",exact:true}).waitFor({state:"hidden"});
    await btn("本步需求与参考").click();
    assert.equal(await page.getByLabel("必须保留的内容与结局方向").inputValue(),"保留最后一声关门");
    assert.ok(await page.getByRole("checkbox",{name:/00-A ·/}).isChecked());
    await btn("关闭").last().click();
    const input = page.getByPlaceholder("输入你的想法，继续完善这一集");
    await input.fill("用已勾选的方法修订。");
    await input.press("Control+Enter");
    await page.waitForFunction(()=>document.querySelector(".composer textarea")?.value==="");
    const story = (await q("episode_view",{episode_id:episode})).artifacts.find(a=>a.stage==="story");
    const run = story.tasks.at(-1).runs.at(-1);
    const selected = (await q("run_methods",{run_id:run.id})).sections.filter(s=>s.source?.enhancementIds);
    assert.deepEqual(selected.map(s=>s.source.enhancementIds),[["00-A"],["00-A"]]);
    await page.goto(base+"/"+preview+"/cast");
    await btn("本集出图增强方法").click();
    await page.getByLabel("本批画面要表现的动作或状态").fill("角色穿着蓝色雨衣");
    await page.getByRole("checkbox",{name:/07-A ·/}).check();
    await btn("保存本步配置").click();
    await page.getByRole("heading",{name:"本步需求",exact:true}).waitFor({state:"hidden"});
    assert.deepEqual((await q("step_config",{episode_id:episode,stage:"assets"})).enhancements,["07-A"]);
    await page.goto(base+"/"+preview+"/assets?tab=canvas");
    await page.getByRole("button",{name:/^＋ .*生成$/}).click();
    await btn("2×2 身份卡").click();
    const canvasPrompt = page.getByRole("textbox").filter({visible:true});
    const texts = await canvasPrompt.evaluateAll(els=>els.map(el=>el.value));
    assert.ok(texts.some(value=>value.includes("正面脸、侧面脸、正面全身、背面全身")));
    await page.getByLabel("跳到画布分区").selectOption("generate");
    const nodeId = await page.getByLabel("定位节点").inputValue();
    assert.ok(nodeId);
    const createdBatch = page.waitForResponse(res=>res.url().endsWith("/cmd/create_batch"));
    await page.getByRole("button",{name:/^生成 [0-9]+ 张/}).click();
    const receipt = await (await createdBatch).json();
    assert.ok(receipt.batchId,JSON.stringify(receipt));
    const batch = await q("batch_view",{batch_id:receipt.batchId});
    assert.equal(batch.state,"awaiting_authorization");
    assert.match(batch.spec.items[0].prompt,/本批画面要表现的动作或状态：角色穿着蓝色雨衣/);
    assert.match(batch.spec.items[0].prompt,/正面脸、侧面脸、正面全身、背面全身/);
    assert.ok(batch.spec.enhancements.every(source=>source.source.enhancementIds.includes("07-A")));
    await page.reload();
    await page.getByLabel("定位节点").selectOption(nodeId);
    await btn("删除").click();
    await page.locator(".modal").getByRole("button",{name:"取消",exact:true}).click();
    assert.equal(await page.getByLabel("定位节点").inputValue(),nodeId);
    await btn("删除").click();
    const saved = page.waitForResponse(res=>res.url().endsWith("/cmd/save_canvas") && res.ok());
    await btn("确认移除节点").click();
    await saved;
    await page.reload();
    await page.getByLabel("定位节点").waitFor();
    assert.ok(!(await q("canvas_view",{episode_id:episode})).doc.nodes.some(n=>n.id===nodeId));
    await page.goto(base+"/"+preview+"/plan");
    const plan = async ()=>(await q("episode_view",{episode_id:episode})).artifacts.find(a=>a.stage==="plan");
    const originalPlan = await plan();
    await page.locator(".shotcard").first().click();
    await btn("删除镜头").click();
    await page.locator(".modal").getByRole("button",{name:"取消",exact:true}).click();
    assert.equal((await plan()).versions.length, originalPlan.versions.length);
    await btn("删除镜头").click();
    const newVersion = page.waitForResponse(res=>res.url().endsWith("/cmd/save_manual") && res.ok());
    await btn("确认删除镜头").click();
    await newVersion;
    const nextPlan = await plan();
    assert.equal(nextPlan.adopted_version_id,originalPlan.adopted_version_id);
    assert.equal(nextPlan.versions.at(-1).content.shots.length,originalPlan.versions.at(-1).content.shots.length-1);
    const token = (await (await page.request.get(base+"/api/session")).json()).token;
    const [image] = await q("episode_assets",{episode_id:episode});
    const added = await page.request.post(base+"/api/cmd/submit_reuse",{
      headers:{"x-adw-token":token},data:{version_id:image.id,usage:"限定正面镜头"}
    });
    assert.equal(added.status(),200);
    await page.goto(base+"/#/p/"+project.id+"/library");
    await page.getByText(image.name,{exact:true}).first().click();
    await btn("限条件").click();
    await page.getByLabel("限制条件",{exact:true}).fill("仅用于正面镜头");
    await page.locator(".modal").getByRole("button",{name:"取消",exact:true}).click();
    await btn("限条件").click();
    assert.equal(await page.getByLabel("限制条件",{exact:true}).inputValue(),"");
    await page.getByLabel("限制条件",{exact:true}).fill("仅用于正面镜头");
    await btn("保存限制条件").click();
    await page.getByText(/限制：仅用于正面镜头/).waitFor();
    await page.reload();
    await page.getByText(image.name,{exact:true}).first().click();
    await page.getByText(/限制：仅用于正面镜头/).waitFor();
    assert.deepEqual(errors,[]);
    console.log("PASS 首页项目、交付入口；71 项选择、保存、写作输入及跨页面出图设置；2×2 身份卡");
  } finally {
    await browser.close();
  }
}
main().catch(e=>{console.error(e);process.exitCode=1;});
